## ============================================================
## Fit the FINAL extended critical-value model (Model I4x)
## ------------------------------------------------------------
##   log c ~ [ 1, log n, log p, log n*log p, p/n, (p/n)^2, (p/n)^3,
##             1/(n-p-1) ]  (8 functions of n,p)
##           x { 1, log m, log^2 m, log^3 m }
##   = 8 x 4 = 32 parameters, fitted by OLS on the rho = 0
##   extended calibration grid (n <= 10000, p <= 500, p < n).
##
## Reads : c_table_ext_full.csv  (from tabulate_c_extended.R BATCH=full)
## Writes: model_I4x_final.rds          (fitted lm object)
##         coefficients_model_I4x.csv   (term, coefficient)
##         coef_block_I4x.R             (R literal used by get_critical_value.R)
## Run   : Rscript fit_final_model.R
## ============================================================

TABLE <- if (file.exists("c_table_ext_full.csv")) "c_table_ext_full.csv" else
         stop("c_table_ext_full.csv not found -- run tabulate_c_extended.R BATCH=full first.")
d <- read.csv(TABLE, stringsAsFactors = FALSE)
d <- d[d$rho == 0, ]
d$logc <- log(d$c)

## ---- canonical 9 x 4 basis --------------------------------
## Order matters: get_critical_value.R rebuilds terms in THIS order.
np_basis <- function(n, p) {
  logn <- log(n); logp <- log(p); pn <- p / n
  list(
    one          = rep(1, length(n)),
    logn         = logn,
    logp         = logp,
    logn_logp    = logn * logp,
    pn           = pn,
    pn2          = pn^2,
    pn3          = pn^3,
    invdf        = 1 / (n - p - 1)         # residual-df correction
  )
}
build_design <- function(df) {
  g   <- np_basis(df$n, df$p)
  lm1 <- log(df$m)
  cols <- list(); nm <- character()
  for (gn in names(g)) for (i in 0:3) {
    cols[[length(cols) + 1]] <- g[[gn]] * lm1^i
    nm <- c(nm, sprintf("%s.logm%d", gn, i))
  }
  X <- do.call(cbind, cols); colnames(X) <- nm; X
}

X   <- build_design(d)
dat <- data.frame(logc = d$logc, X, check.names = FALSE)
fit <- lm(logc ~ 0 + ., data = dat)

## ---- performance ------------------------------------------
pred <- predict(fit)
rel  <- 100 * abs(exp(d$logc) - exp(pred)) / exp(d$logc)
newr <- with(d, !(n <= 1000 & p <= 60))
cat(sprintf("Model I4x  (%d params) fitted on %d points (rho=0)\n",
            length(coef(fit)), nrow(d)))
cat(sprintf("  R^2 = %.5f   RMSE(logc) = %.5f\n",
            summary(fit)$r.squared, sqrt(mean(residuals(fit)^2))))
cat(sprintf("  rel err on c:  median = %.2f%%   90th = %.2f%%   MAX = %.2f%%\n",
            median(rel), quantile(rel, .9), max(rel)))
cat(sprintf("  new region  :  median = %.2f%%   MAX = %.2f%%\n",
            median(rel[newr]), max(rel[newr])))
cat(sprintf("  p/n <= 0.5   :  MAX = %.2f%%\n", max(rel[d$p/d$n <= 0.5])))

## ---- save -------------------------------------------------
saveRDS(fit, "model_I4x_final.rds")
co <- coef(fit)
write.csv(data.frame(term = names(co), coefficient = as.numeric(co)),
          "coefficients_model_I4x.csv", row.names = FALSE)

## R literal for get_critical_value.R (canonical order, no names needed)
con <- file("coef_block_I4x.R", "w")
writeLines("## Auto-generated by fit_final_model.R -- do not edit by hand.", con)
writeLines("## Order: for g in {one,logn,logp,logn_logp,pn,pn2,pn3,invdf}, for i in 0:3.", con)
writeLines("coefs_I4x <- c(", con)
writeLines(paste0("  ", paste(sprintf("%.10g", as.numeric(co)), collapse = ", ")), con)
writeLines(")", con)
close(con)
cat("\nWrote model_I4x_final.rds, coefficients_model_I4x.csv, coef_block_I4x.R\n")
cat("\nCoefficients (canonical order) for pasting:\n")
cat(paste(sprintf("%.10g", as.numeric(co)), collapse = ", "), "\n")
